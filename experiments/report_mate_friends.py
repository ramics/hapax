"""Aggregate the mate-linkage seeds into one table. Tables are generated, never typed.

A number typed into a report is a number without provenance, and this repo has had to
withdraw claims whose prose drifted from its outputs. So `results/mate_friends/TABLES.md`
is built here from the committed per-seed JSONs and the prose in REPORT.md points at it.

The same refusal as `report_pair.py`: a mixture of scripts is not a five-seed result. The
content hash is what pins the code, so seeds are refused when their hashes differ or when a
seed carries none at all, and a dirty tree is recorded rather than refused - it makes the
COMMIT unusable as provenance, not the run.
"""

from __future__ import annotations

import argparse
import glob
import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from subtract_known import provenance

ROOT = Path(__file__).resolve().parents[1]

POPULATIONS = [
    ("permuted_partner_null", "permuted-partner null — read this first"),
    ("mates_disjoint", "**mates sharing no 31-mer** — the honest figure"),
    ("mates_overlap", "mates that overlap, so they share literal bases"),
    ("all", "all mates"),
    ("from_mate1", "mate 1 looking for mate 2"),
    ("from_mate2", "mate 2 looking for mate 1"),
    ("coverage_only", "the four coverage axes alone"),
    ("composition_only", "the six composition axes alone"),
]


def ms(xs) -> str:
    xs = [x for x in xs if x is not None]
    if not xs:
        return "—"
    return (f"{st.mean(xs):.3f} ({min(xs):.3f}–{max(xs):.3f})" if max(xs) - min(xs) > 1e-9
            else f"{st.mean(xs):.3f}")


def pc(xs) -> str:
    return ms([100 * x for x in xs if x is not None])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=ROOT / "results/mate_friends")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    files = sorted(glob.glob(str(args.results / "mate_friends_s*.json")))
    if not files:
        raise SystemExit(f"no seeds in {args.results}")
    ds = [json.loads(Path(f).read_text()) for f in files]
    hashes = {d.get("script_sha256") for d in ds}
    if None in hashes or "" in hashes:
        raise SystemExit("a seed carries no script_sha256, so nothing says which code ran")
    if len(hashes) > 1:
        raise SystemExit(f"these seeds came from different scripts: "
                         f"{[h[:12] for h in hashes]}. A mixture is not a five-seed "
                         f"result; re-run every seed on one commit.")
    dirty = sum(1 for d in ds if d.get("tree_dirty"))
    n = len(ds)
    r = [d["result"] for d in ds]
    k = "10"

    L = [f"# Mate linkage: does a read find its own mate?",
         "",
         f"Generated by `experiments/report_mate_friends.py` from {n} committed seeds. "
         f"Script `{list(hashes)[0][:12]}`, "
         f"{ds[0]['pairs_used']:,} pairs ({ds[0]['mate_points']:,} mate points) per seed, "
         f"k-nearest-neighbour k = {k}."
         + (f" {dirty} of {n} seeds ran while other files in the tree were being edited, "
            f"so their commit names HEAD; the script hash above is identical across all "
            f"{n} and is what pins them." if dirty else ""),
         "",
         "Mean across seeds, with the seed-to-seed range in brackets. Recovery is the "
         "fraction of mates whose own partner is among their 10 nearest neighbours; "
         "chance is 10/(n−1).",
         "",
         "## Recovery at k = 10",
         "",
         "| population | recovery % | × chance |", "|---|---|---|"]
    for key, label in POPULATIONS:
        rec = [x[key][k]["recovery"] for x in r if key in x]
        enr = [x[key][k]["enrichment"] for x in r if key in x]
        L.append(f"| {label} | {pc(rec)} | {ms(enr)} |")
    chance = st.mean([x["all"][k]["chance"] for x in r])
    ov = [x["overlap_rate_of_pairs"] for x in r]
    L += ["", f"Chance is {100 * chance:.4f}%. {pc(ov)}% of pairs share at least one "
              f"canonical 31-mer between their two mates, which is why the disjoint row is "
              f"the honest one: an overlapping pair's two mates contain the same bases, so "
              f"their coverage profiles agree by construction rather than by biology. That "
              f"test is conservative — a shared 31-mer can also come from repeat content — "
              f"so it over-assigns to the overlapping half and leaves the disjoint half "
              f"clean.", ""]

    L += ["## As the space fills", "",
          "Recovery at fixed k depends on how crowded the space is, so a figure from "
          "40,000 points says nothing on its own about 35 million. Whole pairs are "
          "subsampled, never split, and each rung is standardised on its own subsample "
          "because that is what a run of that size would do.", "",
          "| pairs in the space | disjoint recovery % | × chance | all-mate recovery % |",
          "|---|---|---|---|"]
    for i in range(len(r[0]["scale_ladder"])):
        rung = [x["scale_ladder"][i] for x in r]
        L.append(f"| {rung[0]['pairs']:,} | "
                 f"{pc([x['disjoint_recovery_at_10'] for x in rung])} | "
                 f"{ms([x['disjoint_enrichment_at_10'] for x in rung])} | "
                 f"{pc([x['recovery_at_10'] for x in rung])} |")
    L += ["", "The level falls roughly as 1/n while the multiplier **rises**. The far end "
              "is not extrapolated: what a library-scale space does is unmeasured here, "
              "and the figure says where the measurement stops.", ""]

    lm = [x.get("length_matched") for x in r]
    if all(lm):
        L += ["## The two directions, and whether the difference is length", "",
              "Mate 2 is 93 nt against mate 1's 107 after the measured non-template trim, "
              "so it carries 62 scorable 31-mers against 76. The control truncates mate 1 "
              "to mate 2's length and pays a second whole-library pass.", "",
              "| | mate 1 → mate 2 | mate 2 → mate 1 |", "|---|---|---|",
              f"| as sequenced | {pc([x['from_mate1'][k]['recovery'] for x in r])} | "
              f"{pc([x['from_mate2'][k]['recovery'] for x in r])} |",
              f"| mate 1 truncated to 93 nt | "
              f"{pc([x['from_mate1'][k]['recovery'] for x in lm])} | "
              f"{pc([x['from_mate2'][k]['recovery'] for x in lm])} |", ""]

    L += ["## By coverage decile", "",
          "Abundance does most of the work in this geometry already — at 1 in 10,000 the "
          "planted-genome purity is 0.918 on coverage alone against 0.292 on composition "
          "alone — so the decile split is what makes this comparable to the kin wall.", "",
          "| decile | log coverage | recovery % | × chance |", "|---|---|---|---|"]
    for i in range(len(r[0]["by_coverage_decile"])):
        rows = [x["by_coverage_decile"][i] for x in r]
        if rows[0].get("skipped"):
            continue
        lo, hi = rows[0]["log_cov_range"]
        L.append(f"| {i + 1} | {lo:.2f}–{hi:.2f} | "
                 f"{pc([x['recovery_at_10'] for x in rows])} | "
                 f"{ms([x['enrichment_at_10'] for x in rows])} |")
    L += ["", "", "---", "",
          f"Provenance: {json.dumps(provenance(__file__))}", ""]

    out = args.out or (args.results / "TABLES.md")
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))
    print(f"\nwritten {out}")


if __name__ == "__main__":
    main()
