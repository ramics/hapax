#!/usr/bin/env python3
"""Tables for results/pair_search/, generated from the run's own outputs.

Nothing here computes a new statistic. It reads `pairs_<band>.tsv.gz` - one row per pair
per level, carrying every mode's E-value - and prints the three tables the report quotes,
so that no number in the prose is typed by hand:

1. **Mode against mode**, per arm and level, as the five-seed min-max of the pair rate at
   the repo's E < 1e-5 and at each mode's matched-null threshold.
2. **The conversion table**, which is the actual question: of the pairs the single-mate
   baseline does NOT clear, how many does each joint mode clear, and how many does it
   LOSE that the baseline cleared. A mode is only worth something if the first column
   exceeds the second, and a net figure alone hides a mode that trades one for the other.
3. **The junction census** for the concatenated modes: whether any alignment spans the
   point where the two mates were joined. If none does, the searcher is scoring the mates
   independently inside one query while charging both for the combined length, which is
   the mechanism behind concatenation losing rather than gaining.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import json
from collections import defaultdict
from pathlib import Path

MODES = ("best_mate", "concat", "concat_n", "fisher", "agree")
ROOT = Path(__file__).resolve().parents[1]


def load(path: Path):
    """pairs rows -> {(level, arm, seed): {mode: [evalues]}}, keeping pair identity."""
    per = defaultdict(lambda: defaultdict(dict))
    with gzip.open(path, "rt") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            key = (r["level"], r["arm"], r["seed"])
            for m in MODES:
                v = r[f"{m}_e"]
                per[key][r["pair"]][m] = float("inf") if v == "inf" else float(v)
    return per


def rate(cell: dict, mode: str, thr: float) -> float:
    n = len(cell)
    return 100.0 * sum(1 for p in cell.values() if p[mode] < thr) / n if n else 0.0


def spread(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "-"
    lo, hi = min(vals), max(vals)
    return f"{lo:.2f}" if abs(hi - lo) < 5e-3 else f"{lo:.2f}-{hi:.2f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", type=Path, required=True,
                    help="a block directory, e.g. results/pair_search/berlin")
    ap.add_argument("--band", default="near")
    ap.add_argument("--fixed", type=float, default=1e-5)
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args()
    per = load(a.dir / f"pairs_{a.band}.tsv.gz")
    summary = json.loads((a.dir / f"summary_{a.band}.json").read_text())
    levels = sorted({k[0] for k in per})
    arms = sorted({k[1] for k in per})
    out = []

    out.append(f"<!-- generated by experiments/report_pair_search.py from "
               f"{a.dir.name}/pairs_{a.band}.tsv.gz. Do not edit by hand. -->\n")
    for level in levels:
        thr_null = {m: summary["levels"][level]["matched_null_threshold"].get(m)
                    for m in MODES}
        out.append(f"\n## {level}\n")
        out.append("Pair rate, five seeds, min-max. `fixed` is E < "
                   f"{a.fixed:g}; `null` is each mode's strictest threshold at which the "
                   "shuffled arm still reads zero "
                   + ", ".join(f"{m}={thr_null[m] or 'no hit at all'}" for m in MODES)
                   + ".\n")
        out.append("| arm | point | " + " | ".join(MODES) + " |")
        out.append("|---" * (len(MODES) + 2) + "|")
        for arm in arms:
            keys = [k for k in per if k[0] == level and k[1] == arm]
            for point in ("fixed", "null"):
                cells = []
                for m in MODES:
                    thr = a.fixed if point == "fixed" else (
                        float(thr_null[m]) if thr_null[m] else None)
                    cells.append(spread([rate(per[k], m, thr) for k in keys])
                                 if thr is not None else "0 (null never hits)")
                out.append(f"| {arm} | {point} | " + " | ".join(cells) + " |")

        out.append("\n### What each joint mode converts, and what it loses\n")
        out.append("Of the pairs `best_mate` does not clear at E < "
                   f"{a.fixed:g}, the share each mode clears (`gain`); of the pairs it "
                   "does clear, the share that mode loses (`loss`). Five seeds, min-max, "
                   "in pairs per 1,000 so the two are comparable.\n")
        out.append("| arm | mode | gain /1000 | loss /1000 | net /1000 |")
        out.append("|---|---|---|---|---|")
        for arm in arms:
            keys = [k for k in per if k[0] == level and k[1] == arm]
            for m in MODES:
                if m == "best_mate":
                    continue
                g, l, n = [], [], []
                for k in keys:
                    cell = per[k]
                    tot = len(cell) or 1
                    gain = sum(1 for p in cell.values()
                               if p["best_mate"] >= a.fixed and p[m] < a.fixed)
                    loss = sum(1 for p in cell.values()
                               if p["best_mate"] < a.fixed and p[m] >= a.fixed)
                    g.append(1000.0 * gain / tot)
                    l.append(1000.0 * loss / tot)
                    n.append(1000.0 * (gain - loss) / tot)
                out.append(f"| {arm} | {m} | {spread(g)} | {spread(l)} | {spread(n)} |")

        jc = summary["levels"][level].get("junction_census", {})
        if jc:
            out.append("\n### Junction census\n")
            out.append("Every HSP of a concatenated query, by where it lies relative to "
                       "the join. `best_*` counts only each query's best HSP.\n")
            out.append("| placement | HSPs |")
            out.append("|---|---|")
            for k in sorted(jc):
                out.append(f"| {k} | {jc[k]} |")
    text = "\n".join(out) + "\n"
    dest = a.out or (a.dir / "TABLES.md")
    dest.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
