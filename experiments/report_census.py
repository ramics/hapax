"""Aggregate the linkage census seeds into one table. Tables are generated, never typed.

Same refusals as the other aggregators here: a mixture of scripts is not a five-seed
result, so seeds are refused when their content hashes differ or when one carries none.
A dirty tree is recorded rather than refused - it makes the COMMIT unusable as provenance,
not the run, and the content hash is what pins the code.

The table is laid out so the two controls are read before the measurement, because in this
project the control moving with the test has been the tell every time a separator turned
out to be describing the database rather than the reads.
"""

from __future__ import annotations

import argparse
import glob
import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from subtract_known import provenance

ROOT = Path(__file__).resolve().parents[1]

PILES = [
    ("beside_known", "beside sequence we can name (rRNA or identified contigs)"),
    ("beside_assembled_unidentified", "beside contigs that assembled but nothing identified"),
    ("unknown_neighbourhood", "a neighbourhood as unknown as the read"),
    ("mixed", "mixed, no class reaching half"),
    ("no_witnesses", "no witnesses at all, so the census is blind to it"),
]


def pc(xs) -> str:
    xs = [100 * x for x in xs if x is not None]
    if not xs:
        return "not measured"
    return (f"{st.mean(xs):.2f} ({min(xs):.2f}-{max(xs):.2f})" if max(xs) - min(xs) > 1e-9
            else f"{st.mean(xs):.2f}")


def get(d: dict, pile: str, where: str = "piles"):
    v = (d.get(where) or {}).get(pile)
    return v["point"] if v else None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=ROOT / "results/linkage_census")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    files = sorted(glob.glob(str(args.results / "linkage_census_s*.json")))
    if not files:
        raise SystemExit(f"no seeds in {args.results}")
    ds = [json.loads(Path(f).read_text()) for f in files]
    hashes = {d.get("script_sha256") for d in ds}
    if None in hashes or "" in hashes:
        raise SystemExit("a seed carries no script_sha256, so nothing says which code ran")
    if len(hashes) > 1:
        raise SystemExit(f"these seeds came from different scripts: "
                         f"{sorted(h[:12] for h in hashes)}; re-run every seed on one "
                         f"commit before reporting a spread")
    dirty = sum(1 for d in ds if d.get("tree_dirty"))
    n = len(ds)
    par = ds[0]["parameters"]
    R = [d["result"] for d in ds]

    L = ["# The linkage census: what the residue sits next to", "",
         f"Generated by `experiments/report_census.py` from {n} committed seeds. Script "
         f"`{list(hashes)[0][:12]}`, {par['queries']:,} pairs per pile per seed, witnesses "
         f"sharing at least {par['min_shared']} 31-mers, up to {par['max_witnesses']} kept "
         f"per query by reservoir sampling, neighbours labelled at {par['min_mlen']} "
         f"aligned bases - the cascade's own operating point."
         + (f" {dirty} of {n} seeds ran while other files in the tree were being edited, "
            f"so their commit names HEAD; the script hash above pins them." if dirty
            else ""),
         "",
         "Mean across seeds, min-max in brackets, as a percentage of query pairs.",
         "",
         "**Read the two right-hand columns first.** The identified pile is the same census "
         "on reads the cascade did remove; the null is what the piles would read from the "
         "neighbour label mix alone, given each query's number of neighbours.",
         "",
         "| the query sits... | residue | already identified | permuted-label null |",
         "|---|---|---|---|"]
    for key, label in PILES:
        L.append(f"| {label} | **{pc([get(r['residue'], key) for r in R])}** | "
                 f"{pc([get(r['identified'], key) for r in R])} | "
                 f"{pc([get(r['residue'], key, 'permuted_label_null') for r in R])} |")

    L += ["", "## Without the witnesses that overlap their own mate", "",
          "About a third of this library's pairs overlap their mate, so for those the "
          "\"other\" mate is partly the same sequence as the matching one. Dropping every "
          "witness whose two mates both match the query removes that path entirely, at the "
          "cost of moving queries into `no_witnesses`.", "",
          "| the query sits... | residue | already identified |", "|---|---|---|"]
    for key, label in PILES:
        L.append(f"| {label} | "
                 f"{pc([get(r['residue_without_overlapping_witnesses'], key) for r in R])} | "
                 f"{pc([get(r['identified_without_overlapping_witnesses'], key) for r in R])} |")

    L += ["", "## The neighbour label mix", "",
          "What the neighbours themselves are, pooled over queries. This is the input the "
          "null is drawn from, and the difference between the two piles' mixes is the most "
          "robust statement here because it does not depend on the half-of-neighbours rule "
          "that defines the piles above.", "",
          "| neighbour class | residue | already identified |", "|---|---|---|"]
    classes = ds[0]["classes"]
    for c in classes:
        def frac(tag):
            out = []
            for r in R:
                mix = r[tag]["neighbour_label_mix"]
                tot = sum(mix.values())
                out.append(mix[c] / tot if tot else None)
            return out
        L.append(f"| {c} | {pc(frac('residue'))} | {pc(frac('identified'))} |")

    L += ["", "", "---", "", f"Provenance: {json.dumps(provenance(__file__))}", ""]
    out = args.out or (args.results / "TABLES.md")
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwritten {out}")


if __name__ == "__main__":
    main()
