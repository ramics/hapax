    w("  is small enough not to matter at this effect size.")
    w("- One library, one sample. Berlin is a total-RNA preparation; a poly-A or")
    w("  ribodepleted library would not look like this, and the third is a property of this")
    w("  protocol rather than of wastewater.")
    w("- §6 runs one gene caller in one mode. It says what pyrodigal meta does, not what")
    w("  every annotation pipeline does, and the TrEMBL entries §7 implicates were annotated")
    w("  by pipelines not examined here.")
    w("- §8's reach is measured on SSU only, on 8,000 sequences per seed, for stop-free")
    w("  peptide 10-mers. Reach within the index this project actually uses would also")
    w("  depend on which loci were deposited, which is the one route by which §8 and §7 are")
    w("  not independent.")
    w("- §7's attribution is one seed on one UniRef50 subsample, and its control is not")
    w("  abundance-matched, so the ratio of the two heads carries the claim rather than the")
    w("  ribosomal head alone.")
    w("- Nothing here touches sensitivity or the false-positive rate of a novelty call. It")
    w("  explains the composition of a background, which is a different question from")
    w("  whether a read can be scored.")

