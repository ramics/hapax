"""Generate results/rrna_content/REPORT.md from the committed JSON outputs.

The same device as `experiments/fill_peptide_report.py`: every number in the report's
tables is read out of the result files rather than transcribed into prose, because this
project has lost claims to prose that drifted from the outputs it described. Re-run it
after any experiment here and the report follows.
"""

from __future__ import annotations

import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "rrna_content"


def sp(xs):
    return st.mean(xs), (st.stdev(xs) if len(xs) > 1 else 0.0)


def main() -> None:
    content = [json.loads((RES / f"rrna_s{s}.json").read_text()) for s in range(1, 6)]
    ctrl = json.loads((RES / "rrna_control_s1.json").read_text())
    join = json.loads((RES / "rrna_join.json").read_text())
    prod = [json.loads((RES / f"prodigal_on_rrna_s{s}.json").read_text())
            for s in range(1, 6)]
    samp = json.loads((RES / "rrna_sampler_check.json").read_text())

    frac = [c["rrna_fraction_all_reads"] for c in content]
    m, sd = sp(frac)
    idx = content[0]["index"]
    a = join["across_seeds"]

    def row(k):
        return a[k]["mean"], a[k]["sd"]

    t3 = next(t for t in ctrl["thresholds"] if t["min_hits"] == 3)
    sens = t3["sensitivity_heldout_rrna"]

    pr_any, pr_any_sd = sp([p["real_rrna"]["fraction_with_any_call"] for p in prod])
    pr_den, pr_den_sd = sp([p["real_rrna"]["coding_density"] for p in prod])
    sh_den, sh_den_sd = sp([p["composition_shuffled_control"]["coding_density"] for p in prod])
    pr_aa, _ = sp([p["real_rrna"]["amino_acids_called"] for p in prod])
    pr_len, _ = sp([p["real_rrna"]["mean_gene_aa"] for p in prod])
    pr_bp, _ = sp([p["real_rrna"]["total_bp"] for p in prod])

    L = []
    w = L.append
    w("# Ribosomal content of the Berlin library, and what it does to a protein index\n")
    w("Generated by `experiments/fill_rrna_report.py` from the JSON in this directory. Do")
    w("not edit the tables by hand.\n")

    w("## 1. Headline\n")
    w(f"1. **{m*100:.1f}% +/- {sd*100:.1f}% of SRR23973193 reads are ribosomal RNA**, by")
    w("   positive exact 31-mer containment against SILVA 138.1 SSU + LSU NR99. Five seeds,")
    w("   20,000 pairs each, the same read blocks as `experiments/absence_residual.py`.")
    w(f"2. The call is **{sens*100:.1f}% sensitive** on ribosomal sequences held out of the")
    w("   index entirely, so the headline understates the true fraction by a few points at")
    f = row("rrna_given_absent_unmapped")
    w("   most *for taxa that have a close curated relative*. It says nothing about")
    w("   lineages with no near neighbour in SILVA, which are still missed. See §3.")
    w("3. **The abundant-non-coding explanation of the peptide-absence residue is dead.**")
    am, am_sd = row("rrna_given_absent_mapped")
    pm, pm_sd = row("rrna_given_present_mapped")
    w(f"   Ribosomal reads make up {am*100:.1f}% of absent-and-mapped reads but")
    w(f"   {pm*100:.1f}% of present-and-mapped reads. No enrichment, so being ribosomal is")
    w("   not why a mapped read has no peptide match.")
    w(f"4. **The unmapped majority of the residue is not ribosomal either**: {f[0]*100:.1f}%.")
    w("   So \"whole molecules missing from the sample's own assembly\" survives as the")
    w("   reading of that bin, and the rare-and-unsequenced branch keeps the majority.")
    ar, ar_sd = row("absent_given_rrna")
    an, an_sd = row("absent_given_not_rrna")
    w(f"5. **The unexpected result: ribosomal reads are *less* likely to have every peptide")
    w(f"   10-mer absent than anything else**, {ar:.3f} against {an:.3f}. Ribosomal RNA has")
    w("   no true peptide, so an index of real proteins cannot explain this and chance")
    w("   cannot either (§5). Something in the index is matching them.")
    w("6. A gene caller handed nothing but curated ribosomal RNA calls genes on")
    w(f"   {pr_any*100:.1f}% of sequences at a coding density of {pr_den:.3f}, which is real")
    w(f"   spurious protein entering any sample-self index — but a composition-shuffled")
    w(f"   control gives {sh_den:.3f}, *higher*, so this is generic short-ORF calling and")
    w("   not something ribosomal sequence specifically provokes. It is also too small to")
    w("   account for §5 on its own. **The mechanism is therefore established as a real")
    w("   contaminant of the index and NOT established as the explanation of §5.** §6.\n")

    w("## 2. The measurement\n")
    w(f"- Reference: SILVA 138.1 SSURef_NR99 + LSURef_NR99, {idx['sequences']:,} sequences,")
    w(f"  {idx['total_bp']:,} bases.")
    w(f"- Index: canonical {content[0]['k']}-mers, subsampled 1 in")
    w(f"  {int(1/idx['subsample_rate'])} by a splitmix64 hash of the k-mer's own 62-bit")
    w(f"  code, leaving {idx['kmers_retained']:,} distinct codes. Membership is exact, so")
    w("  the structure contributes no false positives; subsampling by a hash of the code")
    w("  keeps the retained set a uniform sample rather than biasing it toward any taxon.")
    w(f"- That {idx['kmers_retained']:,} is far below an eighth of")
    w(f"  {idx['total_bp']:,} positions because ribosomal RNA is conserved enough to be")
    w("  very redundant at this k. The index is 127 MB, which is why this fits at all.")
    w("- A read is called ribosomal at >= 3 retained hits out of the ~9.6 a 107 nt read")
    w("  contributes at this sampling rate.\n")
    w("The sampler is checked rather than trusted (`experiments/rrna_sampler_check.py`),")
    w("because the other branch hit a real bug of exactly this kind: masking the low bits of")
    w("an FNV-style hash over a four-letter alphabet retained 1 k-mer in 65 rather than 1 in")
    w("8, which is invisible in a headline because the same sampling applies to reference and")
    w("query alike. Masking the low bits of a splitmix64 finalizer instead gives a realised")
    w(f"rate of {samp['reference']['realised_rate']:.5f} on reference sequence and")
    w(f"{samp['reads']['realised_rate']:.5f} on reads against a target of")
    w(f"{samp['target_rate']:.5f}, and {samp['retained_kmers_per_read']['mean']:.2f} retained")
    w(f"k-mers per read against {samp['retained_kmers_per_read']['expected']:.2f} expected.\n")
    w("Per seed:\n")
    w("| seed | pairs | rRNA, mate 1 | rRNA, mate 2 | rRNA, all reads |")
    w("| --- | --- | --- | --- | --- |")
    for c in content:
        w(f"| {c['seed']} | {c['pairs']:,} | {c['rrna_fraction']['mate1']:.4f} | "
          f"{c['rrna_fraction']['mate2']:.4f} | {c['rrna_fraction_all_reads']:.4f} |")
    w("")
    h = content[0]["hit_count_histogram"]
    tot = sum(h.values())
    w("The hit count is bimodal, so the threshold is not doing the work. Seed 1, hits per")
    w("read as a fraction of all reads:\n")
    w("| hits | 0 | 1 | 2 | 3 | 4 | 5 | 6 |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    w("| fraction | " + " | ".join(
        f"{h.get(str(i), 0)/tot:.4f}" for i in range(7)) + " |")
    w("")
    w("Only {:.1%} of reads sit in the ambiguous 1-2 band.\n".format(
        (h.get("1", 0) + h.get("2", 0)) / tot))

    w("## 3. Sensitivity and specificity, measured not assumed\n")
    w("`experiments/rrna_control.py`. Every 50th SILVA sequence is held out of the index")
    w(f"and reads are sampled from the held-out ones ({ctrl['sequences_held_out']:,}")
    w(f"sequences, {ctrl['sequences_in_index']:,} left in), at Berlin's measured")
    w(f"substitution rate of {ctrl['error_rate']}. Negatives are")
    w(f"{ctrl['read_length']} nt reads from {len(ctrl['negatives'])} non-ribosomal genomes")
    w("(`data/peptide_noise/`, two of them bacteriophage, so no host sequence either).\n")
    w("| min hits | sensitivity, held-out rRNA | false flag rate, non-rRNA |")
    w("| --- | --- | --- |")
    for t in ctrl["thresholds"]:
        w(f"| >= {t['min_hits']} | {t['sensitivity_heldout_rrna']:.4f} | "
          f"{t['false_flag_rate_non_rrna']:.5f} |")
    w("")
    w(f"At the >= 3 rule used throughout, sensitivity is {sens:.4f} and the false flag rate")
    w(f"{t3['false_flag_rate_non_rrna']:.5f}, so {m*100:.1f}% corrects to")
    w(f"{m/sens*100:.1f}% and the contamination from non-ribosomal sequence is around a")
    w("tenth of a percent against a signal of a third of the library.\n")
    w("**The limit of this control, stated because it bounds the headline's meaning.**")
    w("NR99 is clustered at 99% identity, so a held-out sequence usually has a relative")
    w("about a percent away still in the index. The sensitivity above is therefore the")
    w("sensitivity for organisms that *are* represented in SILVA, and a genuinely divergent")
    w("environmental lineage would still be missed by exact 31-mers. The headline remains a")
    w("lower bound; what this control establishes is that the slack is not in the")
    w("well-represented part, which is where a third of the library evidently sits.\n")

    w("## 4. Where the ribosomal reads sit in the absence residue\n")
    w("`experiments/rrna_join.py`, joined row for row on read_id and mate against")
    w(f"`results/absence_residual/reads_s{{1..5}}.tsv` from {join['residual_source']}.")
    w(f"{join['per_seed'][0]['rows_joined']:,} rows per seed, five seeds; mean (sd) below.\n")
    w("| quantity | mean | sd |")
    w("| --- | --- | --- |")
    for label, key in (
        ("P(every 10-mer absent | ribosomal)", "absent_given_rrna"),
        ("P(every 10-mer absent | not ribosomal)", "absent_given_not_rrna"),
        ("P(ribosomal | absent, mapped)", "rrna_given_absent_mapped"),
        ("P(ribosomal | absent, unmapped)", "rrna_given_absent_unmapped"),
        ("P(ribosomal | present, mapped)", "rrna_given_present_mapped"),
        ("P(ribosomal | present, unmapped)", "rrna_given_present_unmapped"),
        ("P(mapped | ribosomal, not absent)", "mapped_given_rrna_not_absent"),
        ("P(in a called CDS | ribosomal, not absent, mapped)",
         "in_cds_given_rrna_not_absent_mapped"),
        ("P(in a called CDS | ribosomal, absent, mapped)",
         "in_cds_given_rrna_absent_mapped"),
        ("median contig coverage, ribosomal and mapped", "median_cov_rrna_mapped"),
        ("median contig coverage, non-ribosomal and mapped", "median_cov_not_rrna_mapped"),
    ):
        mu, s = row(key)
        w(f"| {label.replace(chr(124), chr(92) + chr(124))} | {mu:.4f} | {s:.4f} |")
    w("")
    w("Three things follow, and two of them contradict predictions both threads wrote down")
    w("in advance.\n")
    w(f"**The mapped part of the residue is not explained by being non-coding.** Ribosomal")
    w(f"reads are {am*100:.1f}% of absent-and-mapped reads and {pm*100:.1f}% of")
    w("present-and-mapped reads. A non-coding explanation of the residue requires")
    w("enrichment and there is none. The branch I proposed in")
    w("`results/peptide_absence_noise/REPORT.md` §11 as a replacement for the withdrawn")
    w("\"absence means wastewater\" claim does not survive its own test.\n")
    w(f"**The unmapped part is not ribosomal**, {f[0]*100:.1f}%. The other branch's reading")
    w("of that bin as whole molecules missing from the sample's own assembly therefore")
    w("stands, and it is the majority of the residue. Both threads predicted 20-30%")
    w("ribosomal there and both were wrong by most of an order of magnitude.\n")
    cm, _ = row("median_cov_rrna_mapped")
    cn, _ = row("median_cov_not_rrna_mapped")
    w(f"**The ribosomal call behaves like ribosomal RNA should**, which is worth saying as a")
    w("check on the method rather than a finding: where these reads map, the contigs carry")
    w(f"median coverage {cm:.0f} against {cn:.0f} for non-ribosomal reads. The most")
    w("abundant thing in a total-RNA library is what it is picking up.\n")

    w("## 5. The result that needed explaining\n")
    w(f"P(absent | ribosomal) = {ar:.3f} against {an:.3f} for everything else. Ribosomal RNA")
    w("encodes no protein, so no real entry in the index can match a ribosomal read, and")
    w("chance cannot do it either: a peptide 10-mer is drawn from a space of about 1e13, the")
    w("index holds about 2.2e8 of them, and a read offers at most 156 10-mers across six")
    w("frames, which puts the chance of any match near 0.3%. The observed 87.5% of")
    w("ribosomal reads having a match is three orders of magnitude away from that. Whatever")
    w("is matching them is in the index for a reason.\n")
    inc_na, _ = row("in_cds_given_rrna_not_absent_mapped")
    inc_a, _ = row("in_cds_given_rrna_absent_mapped")
    mp, _ = row("mapped_given_rrna_not_absent")
    w(f"The non-absent ribosomal reads are {mp*100:.1f}% mapped, and {inc_na:.3f} of them")
    w(f"fall inside a predicted gene against {inc_a:.3f} for the absent ones. The index")
    w("includes proteins predicted by pyrodigal from the sample's own assembly")
    w("(`experiments/absence_residual.py` indexes viral proteins, Swiss-Prot and")
    w("`berlin_sample_proteins.faa`), so gene calls on ribosomal contigs are the obvious")
    w("candidate. §6 tests that, and only partly supports it.\n")

    w("## 6. What a gene caller actually does to ribosomal RNA\n")
    w("`experiments/prodigal_on_rrna.py`. pyrodigal in meta mode, the mode a metagenomic")
    w(f"assembly is annotated with, over {prod[0]['real_rrna']['sequences']:,} SILVA")
    w(f"sequences per seed ({pr_bp/1e6:.2f} Mbp), five seeds. Each sequence is then shuffled,")
    w("preserving length and base composition while destroying every motif, as a control on")
    w("whether ribosomal sequence is specifically prone to this.\n")
    w("| | any gene called | coding density | mean gene length (aa) |")
    w("| --- | --- | --- | --- |")
    w(f"| real rRNA | {pr_any:.4f} ({pr_any_sd:.4f}) | {pr_den:.4f} ({pr_den_sd:.4f}) | "
      f"{pr_len:.0f} |")
    sh_any, sh_any_sd = sp([p["composition_shuffled_control"]["fraction_with_any_call"]
                            for p in prod])
    sh_len, _ = sp([p["composition_shuffled_control"]["mean_gene_aa"] for p in prod])
    w(f"| composition-shuffled | {sh_any:.4f} ({sh_any_sd:.4f}) | {sh_den:.4f} "
      f"({sh_den_sd:.4f}) | {sh_len:.0f} |")
    w("")
    w(f"So a gene caller does invent protein on ribosomal RNA, and at scale: {pr_aa:,.0f}")
    w(f"amino acids from {pr_bp/1e6:.2f} Mbp, on {pr_any*100:.0f}% of sequences. Every")
    w("sample-self protein index built by annotating an assembly and indexing the result")
    w("carries this, and ribosomal contigs are among the highest-coverage contigs in a")
    w("total-RNA library, so there are plenty of them.\n")
    w("Two honest limits on that, both of which cut against the strong form of the claim.\n")
    w(f"First, the shuffled control calls *more* ({sh_den:.3f} against {pr_den:.3f}), so this")
    w("is generic short-ORF calling on sequence of this composition and not something")
    w(f"ribosomal structure provokes. Mean called length is {pr_len:.0f} aa, which is short.")
    w("The phenomenon is a property of running a gene caller on anything, and ribosomal RNA")
    w("is simply the most abundant anything in this library.\n")
    w(f"Second, {pr_den:.3f} coding density is well below the {prod[0]['comparison']['berlin_assembly_coding_density']}")
    w("the other branch measured across the whole Berlin assembly, and below the")
    w(f"{inc_na:.3f} of non-absent ribosomal reads that fall inside a call. A density of")
    w(f"{pr_den:.3f} cannot by itself put {(1-ar)*100:.0f}% of ribosomal reads inside reach")
    w("of a spurious peptide. Either the spurious peptides are matched by reads outside")
    w("their own contig's calls, which ribosomal conservation makes easy, or part of §5 has")
    w("another cause, the obvious candidate being that translated ribosomal RNA is")
    w("low-complexity and matches the low-complexity regions of real proteins.\n")
    w("**So §6 establishes that this contaminates the index and does not establish that it")
    w("explains §5.** The decisive test is to rebuild the index with proteins from")
    w("ribosomal contigs excluded and re-measure P(absent | ribosomal): if the mechanism is")
    w(f"the explanation it should rise toward {an:.3f}, and if it is not it will stay near")
    w(f"{ar:.3f}. That test needs the assembly and the annotation, so it belongs to the")
    w("branch that holds them, and it is running there.\n")

    w("## 7. What this costs the thesis, after the other branch narrowed it\n")
    w("The deliverable in view is a curve of background reads removed against index size,")
    w("and the cheapest large step on it so far was adding the sample's own predicted")
    w("proteins, which took absence from 86.3% to around 22%. §6 raised the worry that part")
    w("of that step was a gene caller explaining ribosomal reads with protein that does not")
    w("exist. **It is not, and the worry is withdrawn at that scale.** The other branch")
    w("labelled the assembly rather than the reads and found ribosomal contigs to be 1.72%")
    w("of assembly bases carrying 388 of 79,667 proteins and 19,137 of 8,042,848 indexed")
    w("residues, 0.24%, stable from a hit-fraction threshold of 0.5 down to 0.05. A quarter")
    w("of one percent of the index cannot move 86% to 22%, so that step stands as background")
    w("removal. Their coding density on those contigs, 0.281, also agrees with the 0.164")
    w("measured here on reference sequence, which is the main reason to trust either.\n")
    w("What the 0.24% does *not* settle is §5, and the distinction is worth keeping because")
    w("it is easy to apply the number to the wrong question. A read stops being fully absent")
    w("as soon as one of its 10-mers matches anything, so what governs P(absent | ribosomal)")
    w("is not the spurious proteins' share of the index but the chance a ribosomal read")
    w("falls within reach of one of them. That is a coverage quantity: their 0.281 on")
    w(f"ribosomal contigs, and the {inc_na:.3f} and {inc_a:.3f} in §4 weight to about 0.38 of")
    w("mapped ribosomal reads sitting inside a call. Two orders above 0.0024. So the")
    w("mechanism plausibly accounts for roughly a third of the ribosomal reads that have a")
    w("match, and the rest needs another cause.\n")
    w("The discriminating test is theirs and is running: rebuild the index with those 388")
    w("proteins excluded and re-measure. Both threads have put a number on it in advance —")
    w(f"this one expects P(absent | ribosomal) to move from {ar:.3f} to near 0.4, the other")
    w("to 0.25-0.35 on the grounds that a spurious 71 aa call is matched by other ribosomal")
    w("reads only where the underlying rRNA is conserved, which SILVA's own clustering says")
    w("is patchy. The remaining candidate for whatever is left is that translated ribosomal")
    w("RNA is low-complexity and matches the low-complexity regions of real proteins, which")
    w("is being measured in the same run.\n")
    w("Masking ribosomal sequence before annotating is still worth doing, but as hygiene")
    w("rather than as a correction to the curve.\n")
    w("The other half of the ledger is unaffected and simply useful. A third of this library")
    w("is ribosomal and a protein index can never match it, so a third of the sequencing is")
    w("being spent on material the whole approach is structurally blind to. That is an")
    w("argument about library preparation, not about indexing, and it is the first number in")
    w("this project that bears on it.\n")
    w("## 8. What this does not establish\n")
    w("- Sensitivity is measured against a 99%-clustered reference, so it speaks for")
    w("  represented taxa only (§3). A divergent environmental lineage is still missed and")
    w("  the headline stays a lower bound.")
    w("- Ribosomal status is called per read. A read on a contig that is partly ribosomal")
    w("  and partly not is called ribosomal, which is one reason the in_cds figures here and")
    w("  a contig-level labelling need not agree.")
    w(f"- {samp['uncallable_read_fraction']*100:.2f}% of reads carry fewer than 3 retained")
    w("  k-mers, from ambiguous bases or length, so they can never be called ribosomal at")
    w("  any threshold. That is a ceiling on sensitivity rather than a tuning choice, and it")
    w("  is small enough not to matter at this effect size.")
    w("- One library, one sample. Berlin is a total-RNA preparation; a poly-A or")
    w("  ribodepleted library would not look like this, and the third is a property of this")
    w("  protocol rather than of wastewater.")
    w("- §6 runs one gene caller in one mode. It says what pyrodigal meta does, not what")
    w("  every annotation pipeline does.")
    w("- Nothing here touches sensitivity or the false-positive rate of a novelty call. It")
    w("  explains the composition of a background, which is a different question from")
    w("  whether a read can be scored.")

    (RES / "REPORT.md").write_text("\n".join(L) + "\n")
    print(f"wrote {RES / 'REPORT.md'}")


if __name__ == "__main__":
    main()
